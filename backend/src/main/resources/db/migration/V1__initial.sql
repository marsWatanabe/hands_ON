-- ユーザー（JPA エンティティ User。テーブル名は @Table(name = "_user") に合わせる）
CREATE TABLE _user (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname   VARCHAR(100) NOT NULL,
    lastname    VARCHAR(100) NOT NULL,
    email       VARCHAR(255) NOT NULL,
    password    VARCHAR(255) NOT NULL,
    role        VARCHAR(50)  NOT NULL DEFAULT 'USER',
    CONSTRAINT uk_user_email UNIQUE (email),
    CONSTRAINT chk_user_role CHECK (role IN ('USER', 'ADMIN'))
);

-- カテゴリ情報（部品・製品共通。category_type で区分）
CREATE TABLE category_info (
    category_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_type  VARCHAR(10)  NOT NULL,
    category_name  VARCHAR(20)  NOT NULL,
    description    VARCHAR(255),
    delete_flag    SMALLINT     NOT NULL DEFAULT 0,
    create_date    TIMESTAMP,
    update_date    TIMESTAMP,
    CONSTRAINT chk_category_type        CHECK (category_type IN ('part', 'product')),
    CONSTRAINT chk_category_delete_flag CHECK (delete_flag IN (0, 1))
);

-- 在庫センター情報
CREATE TABLE center_info (
    center_id                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_name               VARCHAR(20)  NOT NULL,
    post_code                 VARCHAR(10)  NOT NULL,
    address                   VARCHAR(255) NOT NULL,
    phone_number              VARCHAR(20)  NOT NULL,
    manager_name              VARCHAR(100) NOT NULL,
    operational_status        SMALLINT     NOT NULL DEFAULT 0,
    max_storage_capacity      INT,
    current_storage_capacity  INT,
    notes                     VARCHAR(255),
    delete_flag               SMALLINT     NOT NULL DEFAULT 0,
    create_date               TIMESTAMP,
    update_date               TIMESTAMP,
    -- API 仕様書: センター名は重複禁止（DB ユニーク制約）。削除済みを含めるかは未決（requirements.md Q-5）。
    CONSTRAINT uk_center_name              UNIQUE (center_name),
    CONSTRAINT chk_center_status           CHECK (operational_status IN (0, 1)),
    CONSTRAINT chk_center_delete_flag      CHECK (delete_flag IN (0, 1)),
    CONSTRAINT chk_center_max_capacity     CHECK (max_storage_capacity IS NULL OR max_storage_capacity >= 0),
    CONSTRAINT chk_center_current_capacity CHECK (current_storage_capacity IS NULL OR current_storage_capacity >= 0)
);

-- 部品在庫情報（category_info の種別が 'part' であることはアプリ側で検証する）
CREATE TABLE parts_stock_info (
    stock_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  INT,
    name         VARCHAR(255) NOT NULL,
    center_id    INT,
    description  VARCHAR(255),
    amount       INT,
    delete_flag  SMALLINT     NOT NULL DEFAULT 0,
    create_date  TIMESTAMP,
    update_date  TIMESTAMP,
    CONSTRAINT fk_parts_category     FOREIGN KEY (category_id) REFERENCES category_info (category_id),
    CONSTRAINT fk_parts_center       FOREIGN KEY (center_id)   REFERENCES center_info (center_id),
    CONSTRAINT chk_parts_amount      CHECK (amount IS NULL OR amount >= 0),
    CONSTRAINT chk_parts_delete_flag CHECK (delete_flag IN (0, 1))
);
CREATE INDEX idx_parts_stock_category ON parts_stock_info (category_id);
CREATE INDEX idx_parts_stock_center   ON parts_stock_info (center_id);

-- 製品在庫情報（category_info の種別が 'product' であることはアプリ側で検証する）
CREATE TABLE products_stock_info (
    stock_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  INT,
    name         VARCHAR(255) NOT NULL,
    center_id    INT,
    description  VARCHAR(255),
    amount       INT,
    delete_flag  SMALLINT     NOT NULL DEFAULT 0,
    create_date  TIMESTAMP,
    update_date  TIMESTAMP,
    CONSTRAINT fk_products_category     FOREIGN KEY (category_id) REFERENCES category_info (category_id),
    CONSTRAINT fk_products_center       FOREIGN KEY (center_id)   REFERENCES center_info (center_id),
    CONSTRAINT chk_products_amount      CHECK (amount IS NULL OR amount >= 0),
    CONSTRAINT chk_products_delete_flag CHECK (delete_flag IN (0, 1))
);
CREATE INDEX idx_products_stock_category ON products_stock_info (category_id);
CREATE INDEX idx_products_stock_center   ON products_stock_info (center_id);
